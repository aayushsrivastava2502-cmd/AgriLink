def get_current_language():
    """Retrieve the active language code: 'en' or 'hi'."""
    # 1. From active session
    if session:
        lang = session.get("lang")
        if lang in SUPPORTED_LANGUAGES:
            return lang
    # 2. From request query params (if set on the fly)
    if request:
        arg_lang = request.args.get("lang")
        if arg_lang in SUPPORTED_LANGUAGES:
            if session:
                session["lang"] = arg_lang
            return arg_lang
        # 3. Check Accept-Language header
        accept = request.headers.get("Accept-Language", "")
        if "hi" in accept.lower()[:5]:
            return "hi"
    return DEFAULT_LANGUAGE


def set_current_language(lang_code):
    """Persist language code into session after validation."""
    if lang_code in SUPPORTED_LANGUAGES:
        session["lang"] = lang_code
        return True
    return False


def translate(text, lang=None, **kwargs):
    """Translate a text string to the target language (default current language)."""
    if not text:
        return ""
    target_lang = lang or get_current_language()
    clean = str(text).strip()
    if target_lang == "hi":
        res = TRANSLATIONS_HI.get(clean, clean)
    else:
        res = clean
    if kwargs:
        try:
            return res.format(**kwargs)
        except Exception:
            return res
    return res


# Aliases for clean templating and code
_ = translate
t = translate


def get_js_translations_dict():
    """Export frontend localized strings for JavaScript (maps, charts, forms)."""
    lang = get_current_language()
    return JS_TRANSLATIONS.get(lang, JS_TRANSLATIONS["en"])
